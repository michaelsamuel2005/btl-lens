"""Post-launch evaluation of the instant AVM remortgage option.

    python -m analysis.feature_impact       # after `dbt build`

Reads marts.fct_feature_impact, estimates the launch's effect on days to offer and on withdrawals by
difference-in-differences (eligible remortgages against ineligible ones, before and after launch), with
confidence intervals, and writes outputs/feature_impact.json, docs/FEATURE_IMPACT.md and two charts. The
simulator's designed effect (data/ground_truth/feature_effect.json) is read only at the end, to check the estimate.
"""
from __future__ import annotations

import json
from pathlib import Path

import duckdb
import matplotlib
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "outputs" / "btl_lens.duckdb"
IMG = ROOT / "docs" / "img"
BLUE, GREY, RED = "#2f6db5", "#8a8f98", "#c0392b"


def load(db: Path = DB) -> pd.DataFrame:
    con = duckdb.connect(str(db), read_only=True)
    df = con.sql("select * from marts.fct_feature_impact").df()
    df["eligible"] = df.feature_eligible.astype(int)
    df["post"] = df.is_post_launch.astype(int)
    df["withdrawn"] = df.is_withdrawn.astype(int)
    return df


def did(df: pd.DataFrame, outcome: str, subset: pd.Series | None = None) -> dict:
    d = df if subset is None else df[subset]
    m = smf.ols(f"{outcome} ~ eligible * post", data=d).fit(cov_type="HC1")
    est, se = m.params["eligible:post"], m.bse["eligible:post"]
    cells = d.groupby(["eligible", "post"])[outcome].agg(["mean", "count"])
    return {
        "estimate": float(est), "se": float(se), "ci95": [float(est - 1.96 * se), float(est + 1.96 * se)],
        "p_value": float(m.pvalues["eligible:post"]), "n": int(m.nobs),
        "cells": {f"{'eligible' if e else 'ineligible'}_{'post' if p else 'pre'}": {"mean": float(r["mean"]), "n": int(r["count"])}
                  for (e, p), r in cells.iterrows()},
        "naive_before_after_eligible": float(cells.loc[(1, 1), "mean"] - cells.loc[(1, 0), "mean"]),
    }


def monthly_chart(df: pd.DataFrame, launch: str, path: Path) -> None:
    d = df[df.reached_offer].copy()
    d["month"] = pd.to_datetime(d.submitted_month)
    g = d.groupby(["month", "analysis_group"]).days_to_offer.mean().unstack()
    fig, ax = plt.subplots(figsize=(8, 3.6))
    ax.plot(g.index, g["eligible"], color=BLUE, lw=2, label="Eligible remortgages")
    ax.plot(g.index, g["ineligible"], color=GREY, lw=2, label="Ineligible remortgages (comparison)")
    ax.axvline(pd.Timestamp(launch), color=RED, lw=1, ls="--")
    ax.text(pd.Timestamp(launch), ax.get_ylim()[1] * 0.97, " launch", color=RED, va="top", fontsize=9)
    ax.set_ylabel("Mean days from submission to offer")
    ax.set_xlabel("Month submitted")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def avm_chart(df: pd.DataFrame, launch: str, path: Path) -> None:
    d = df[df.feature_eligible].copy()
    d["month"] = pd.to_datetime(d.submitted_month)
    g = d.groupby("month").avm_used.mean()
    fig, ax = plt.subplots(figsize=(8, 3.0))
    ax.bar(g.index, g.values * 100, width=20, color=BLUE)
    ax.axvline(pd.Timestamp(launch), color=RED, lw=1, ls="--")
    ax.set_ylabel("AVM used (% of eligible cases)")
    ax.set_xlabel("Month submitted")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def write_note(res: dict, truth: dict, path: Path) -> None:
    d, w = res["days_to_offer"], res["withdrawal_rate"]
    c = d["cells"]
    cw = w["cells"]
    exp = truth["expected_effect_on_eligible_group"]
    in_ci_days = d["ci95"][0] <= exp["days_to_offer"] <= d["ci95"][1]
    in_ci_w = w["ci95"][0] <= exp["withdrawal_rate"] <= w["ci95"][1]
    text = f"""# Instant AVM remortgage: what changed after launch

*A post-launch evaluation written for a product manager. Generated by `analysis/feature_impact.py` from the
`fct_feature_impact` mart; every number here is computed, not typed.*

## The question

On {res['launch_date']} the broker portal started offering an automated valuation (AVM) instead of a physical
valuation on eligible remortgages: standard properties and small HMOs, up to {truth['eligible']['max_ltv_pct']:.0f}% LTV, for landlords with up to
{truth['eligible']['max_portfolio_size']} mortgaged properties. A physical valuation takes one to two weeks to come back; an AVM comes back in a day
or two. Did offers get faster, and did fewer brokers walk away while waiting?

## The answer

**Eligible remortgages reach offer {abs(d['estimate']):.1f} days sooner because of the feature** (95% confidence interval
{abs(d['ci95'][1]):.1f} to {abs(d['ci95'][0]):.1f} days), from a mean of {c['eligible_pre']['mean']:.1f} days before launch. About {res['avm_take_up_post']:.0%} of eligible cases
chose the AVM, so for the cases that used it the saving is larger, roughly {abs(d['estimate']) / res['avm_take_up_post']:.0f} days.

**Withdrawals fell by {abs(w['estimate']) * 100:.1f} percentage points** among eligible cases (95% CI {abs(w['ci95'][1]) * 100:.1f} to {abs(w['ci95'][0]) * 100:.1f} points), from
{cw['eligible_pre']['mean']:.1%} before launch. The interval is wide: only {cw['eligible_post']['n']:,} eligible applications were submitted after launch that are old enough to
have resolved, and a yes-or-no outcome carries far less information than a number of days. Treat the withdrawal result as
directional until there are more months of data.

![Days to offer by month](img/feature_days_to_offer.png)

![AVM take-up among eligible cases](img/feature_avm_take_up.png)

## How it was measured, and two traps avoided

**Comparison group.** Ineligible remortgages (multi-unit blocks, over {truth['eligible']['max_ltv_pct']:.0f}% LTV, large portfolios) could not use the
feature, so their change over the same months shows what would have happened anyway. Their days to offer moved by
{c['ineligible_post']['mean'] - c['ineligible_pre']['mean']:+.1f} days ({c['ineligible_pre']['mean']:.1f} to {c['ineligible_post']['mean']:.1f}) because underwriting got quicker for everyone in 2026. A simple before-and-after
on eligible cases alone would have claimed {abs(d['naive_before_after_eligible']):.1f} days, crediting the feature with that general improvement. The
difference-in-differences estimate removes it.

**Censoring.** Cases submitted in the last {res['censoring_days']} days of the data are excluded. Among the most recent submissions,
only the quick ones have an offer yet, so including them would make the post-launch period look faster than it is.

Standard errors are heteroskedasticity-robust (HC1) from an OLS regression of the outcome on eligibility, period
and their interaction, on {d['n']:,} remortgage applications that reached offer (timing) and {w['n']:,} applications (withdrawals).

## Check against the simulation's designed effect

This is simulated data, so the true effect is known (read only after estimating): the feature was built to save
{truth['true_effects']['avm_valuation_days_saved']:.1f} days of valuation time on {truth['avm_take_up']:.0%} of eligible cases, an expected {exp['days_to_offer']:+.1f} days on the eligible group, and to cut
withdrawals by {abs(exp['withdrawal_rate']) * 100:.1f} points. The days-to-offer estimate {'contains' if in_ci_days else 'does not contain'} the designed effect in its 95% interval;
the withdrawal estimate {'does' if in_ci_w else 'does not'}.

## What to watch next

- Take-up: {res['avm_take_up_post']:.0%} of eligible cases chose the AVM. Which broker networks are not using it, and why?
- Valuation quality: AVM market values against later physical valuations on the same properties, before extending
  eligibility to higher LTVs.
- Policy: {res['avm_ineligible_count']} AVMs were run on cases outside the eligibility rules (see the data-quality register).
"""
    path.write_text(text)


def main() -> dict:
    df = load()
    con = duckdb.connect(str(DB), read_only=True)
    import yaml
    proj = yaml.safe_load((ROOT / "dbt" / "dbt_project.yml").read_text())
    launch = str(proj["vars"]["feature_launch_date"])
    res = {
        "launch_date": launch,
        "censoring_days": int(proj["vars"]["analysis_censoring_days"]),
        "days_to_offer": did(df, "days_to_offer", df.reached_offer),
        "withdrawal_rate": did(df, "withdrawn"),
        "avm_take_up_post": float(df[(df.feature_eligible) & (df.is_post_launch)].avm_used.mean()),
        "avm_ineligible_count": int(con.sql("select count(*) from quality.dq_issues where issue_type = 'avm_ineligible'").fetchone()[0]),
    }
    IMG.mkdir(parents=True, exist_ok=True)
    monthly_chart(df, launch, IMG / "feature_days_to_offer.png")
    avm_chart(df, launch, IMG / "feature_avm_take_up.png")
    truth = json.loads((ROOT / "data" / "ground_truth" / "feature_effect.json").read_text())
    res["designed_effect"] = truth["expected_effect_on_eligible_group"]
    res["designed_effect_within_ci"] = {
        "days_to_offer": bool(res["days_to_offer"]["ci95"][0] <= truth["expected_effect_on_eligible_group"]["days_to_offer"] <= res["days_to_offer"]["ci95"][1]),
        "withdrawal_rate": bool(res["withdrawal_rate"]["ci95"][0] <= truth["expected_effect_on_eligible_group"]["withdrawal_rate"] <= res["withdrawal_rate"]["ci95"][1]),
    }
    (ROOT / "outputs" / "feature_impact.json").write_text(json.dumps(res, indent=2))
    write_note(res, truth, ROOT / "docs" / "FEATURE_IMPACT.md")
    return res


if __name__ == "__main__":
    r = main()
    d, w = r["days_to_offer"], r["withdrawal_rate"]
    print(f"days to offer: DiD {d['estimate']:+.2f} days (95% CI {d['ci95'][0]:+.2f} to {d['ci95'][1]:+.2f}); naive before/after {d['naive_before_after_eligible']:+.2f}; designed {r['designed_effect']['days_to_offer']:+.2f}")
    print(f"withdrawals:   DiD {w['estimate'] * 100:+.2f} pp (95% CI {w['ci95'][0] * 100:+.2f} to {w['ci95'][1] * 100:+.2f}); designed {r['designed_effect']['withdrawal_rate'] * 100:+.2f}")
    print("designed effect within CI:", r["designed_effect_within_ci"])
